// Builds docs/sql/app_single_migration.sql — the WHOLE migration lineage
// (every migrations/NNNN_name.sql, in order, verbatim) as one file a DBA runs
// once with psql to stand up a fresh database without the Node runner.
//
// The bundle is EQUIVALENT to `node scripts/migrate.mjs up` on an empty
// database, by construction: same files, same order, nothing rewritten. It
// also records every migration in public.app_migrations, so the runner (and
// any future numbered migration) still works against a bundle-created
// database — the two paths stay interchangeable.
//
// Regenerate (and commit the output) whenever a migration lands:
//   node scripts/build-single-migration.mjs
//
// Usage of the OUTPUT, on an empty database the caller creates:
//   psql -v ON_ERROR_STOP=1 -d app_db -f docs/sql/app_single_migration.sql
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const migrationsDir = path.join(here, '..', 'migrations')
const outFile = path.join(here, '..', '..', 'docs', 'sql', 'app_single_migration.sql')

const files = (await readdir(migrationsDir))
  .filter((f) => f.endsWith('.sql') && !f.endsWith('.down.sql'))
  .sort()

const first = files[0].slice(0, 4)
const last = files[files.length - 1].slice(0, 4)

const parts = [
  `-- app_db — the full migration lineage ${first}–${last} as ONE file.`,
  '--',
  '-- GENERATED by backend/scripts/build-single-migration.mjs. Do not edit;',
  '-- regenerate after any new migration. Each numbered section below is the',
  '-- corresponding backend/migrations file, VERBATIM and in order — this',
  '-- bundle and `node scripts/migrate.mjs up` produce identical databases.',
  '--',
  '-- Run once, on an EMPTY database you create first:',
  '--   psql -v ON_ERROR_STOP=1 -d app_db -f app_single_migration.sql',
  '--',
  '-- Everything runs in one transaction: any error rolls back the lot.',
  '-- The final section records the lineage in public.app_migrations, so the',
  '-- Node runner recognises this database and future numbered migrations',
  '-- apply on top normally.',
  '',
  "SET client_encoding = 'UTF8';",
  'BEGIN;',
  '',
]

for (const f of files) {
  const body = (await readFile(path.join(migrationsDir, f), 'utf8')).replace(/\r\n/g, '\n')
  parts.push(
    '-- ============================================================================',
    `-- ${f}`,
    '-- ============================================================================',
    '',
    body.trimEnd(),
    '',
  )
}

parts.push(
  '-- ============================================================================',
  '-- migration bookkeeping — mark the whole lineage applied',
  '-- ============================================================================',
  '',
  '-- Some target databases have no public schema; the runner recreates it the',
  '-- same way — see scripts/migrate.mjs.',
  'CREATE SCHEMA IF NOT EXISTS public;',
  'CREATE TABLE IF NOT EXISTS public.app_migrations (',
  '    name       TEXT PRIMARY KEY,',
  '    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()',
  ');',
  'INSERT INTO public.app_migrations (name) VALUES',
  files.map((f) => `    ('${f}')`).join(',\n') + ';',
  '',
  'COMMIT;',
  '',
)

await mkdir(path.dirname(outFile), { recursive: true })
await writeFile(outFile, parts.join('\n'), 'utf8')
console.log(`wrote ${outFile} — ${files.length} migrations (${first}–${last})`)
